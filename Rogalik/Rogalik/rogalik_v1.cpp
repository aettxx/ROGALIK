int count_who_is_moving = 0; // Очередь хода (кто ходит сейчас)
int count_G = 10;



void movePlayer(Player& pl, string player_name) { // Ход игрока и проверка на аптеки и тварей
	int next_x = pl.x;
	int next_y = pl.y;

	cout << "Ход " << player_name << ":" << "\n";
	cout << "Здоровье " << player_name << ": " << pl.hp << "\n";
	cout << "Осталось гоблинов: " << count_G << "\n";

	if (count_who_is_moving % 2 == 0) {
		char move = _getch();


		if (move == 'd' || move == 'в') {
			next_x++;
		}
		if (move == 'a' || move == 'ф') {
			next_x--;
		}
		if (move == 's' || move == 'ы') {
			next_y++;
		}
		if (move == 'w' || move == 'ц') {
			next_y--;
		}
	}
	else {
		int move = _getch();
		if (move == 224) {
			move = _getch();
			if (move == 77) {
				next_x++;
			}
			if (move == 75) {
				next_x--;
			}
			if (move == 80) {
				next_y++;
			}
			if (move == 72) {
				next_y--;
			}
		}
	}
	if (gamemap[next_y][next_x] != '#') {
		pl.y = next_y;
		pl.x = next_x;
		if (gamemap[next_y][next_x] == 'G') {
			gamemap[next_y][next_x] = '.';
			pl.hp -= 30;
			count_G--;
		}
		if (gamemap[next_y][next_x] == 'H') {
			pl.hp += 20;
			if (pl.hp > 100) {
				pl.hp = 100;
			}
			gamemap[next_y][next_x] = '.';
		}
	}
	count_who_is_moving++;
}




